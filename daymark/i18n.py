def set_language(code: str) -> str:
    """Select a supported language; stale Persian preferences migrate to English."""
    global _LANGUAGE
    _LANGUAGE = code if code in LANGUAGES else "en"
    try:
        from .qt import QApplication, Qt

        app = QApplication.instance()
        if app is not None:
            app.setLayoutDirection(Qt.LayoutDirection.LeftToRight)
    except ImportError:
        pass
    return _LANGUAGE


def language() -> str:
    return _LANGUAGE


def is_rtl() -> bool:
    return False


def t(key: str, **values) -> str:
    value = _TRANSLATIONS.get(_LANGUAGE, _TRANSLATIONS["en"]).get(
        key, _TRANSLATIONS["en"].get(key, key)
    )
    try:
        return value.format(**values)
    except (KeyError, ValueError):
        return value


def language_items() -> list[tuple[str, str]]:
    return [("English", "en"), ("Türkçe", "tr")]


def localize_digits(value: object) -> str:
    return str(value)


def normalize_digits(value: object) -> str:
    # Keep accepting Arabic/Persian digits in pasted numeric values even though
    # the Persian interface is no longer available.
    return str(value).translate(
        str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")
    )


def apply_text_input_direction(root=None) -> None:
    """Compatibility hook retained for callers; both supported languages are LTR."""
    return None


def install_text_input_direction_support() -> None:
    """No event filter is required for the English/Turkish LTR interface."""
    return None


def task_count(count: int, active: bool = False) -> str:
    key = ("active_count_one" if count == 1 else "active_count_many") if active else (
        "task_count_one" if count == 1 else "task_count_many"
    )
    return t(key, count=localize_digits(count))
